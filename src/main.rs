fn build_and_train_model() -> SentenceTransformer {
    let mut tokenizer = SimpleTokenizer::new();

    // Collect initial vocabulary from sample pairs
    let sample_data = get_sample_dataset();
    let mut corpus: Vec<&str> = Vec::new();
    for pair in &sample_data {
        corpus.push(pair.sent_a);
        corpus.push(pair.sent_b);
    }
    // Add extra common domain vocabulary
    corpus.push("transformer multi head self attention query key value vector embeddings");
    corpus.push("natural language processing dense representations cosine similarity semantic search");
    corpus.push("rust high performance memory safe systems programming machine learning");

    tokenizer.build_vocab(&corpus);

    // Hyperparameters for our POC Sentence Transformer
    let d_model = 64; // Embedding dimension
    let num_heads = 4; // 4 attention heads (d_k = 16 per head)
    let d_ff = 128; // Feed-forward hidden dimension
    let num_layers = 2; // 2 stacked Transformer Encoder layers
    let max_seq_len = 32; // Maximum tokens per sentence

    let mut model = SentenceTransformer::new(
        tokenizer,
        d_model,
        num_heads,
        d_ff,
        num_layers,
        max_seq_len,
    );

    // Run POC training for 200 epochs (demonstrating loss convergence across iterations)
    train_poc_sentence_transformer(&mut model, 200, 0.05);

    model
}

/// Save embeddings to both formatted JSON and human-readable Markdown/Text files
fn save_embeddings_to_files(
    results: &[SentenceEmbeddingResult],
    similarities: &[(String, String, f32)],
) -> io::Result<()> {
    // 1. JSON file
    let json_file_path = "embeddings_output.json";
    let json_file = File::create(json_file_path)?;
    serde_json::to_writer_pretty(json_file, &results)?;
    println!(" [FILE SAVED] Full raw embeddings saved to: {}", json_file_path);

    // 2. Markdown / Text file for presentation
    let md_file_path = "embeddings_output.md";
    let mut md_file = File::create(md_file_path)?;

    writeln!(md_file, "# Sentence Transformer - Embeddings Output Log")?;
    writeln!(md_file, "Generated by: Pure Rust Transformer Proof-of-Concept\n")?;
    writeln!(md_file, "## Model Architecture Details")?;
    writeln!(md_file, "- **Type**: Encoder-only Sentence Transformer (MiniLM-style)")?;
    writeln!(md_file, "- **Model Dimension ($d_{{model}}$)**: 64")?;
    writeln!(md_file, "- **Attention Heads**: 4 ($d_k = 16$)")?;
    writeln!(md_file, "- **Encoder Layers**: 2")?;
    writeln!(md_file, "- **Pooling**: Mean Pooling over active tokens + L2 Normalization")?;
    writeln!(md_file, "- **Vector Space**: Unit Hypersphere ($||v||_2 = 1.0$)\n")?;
    writeln!(md_file, "---\n")?;

    writeln!(md_file, "## Generated Sentence Embeddings\n")?;

    for (idx, res) in results.iter().enumerate() {
        writeln!(md_file, "### Sentence #{}: \"{}\"", idx + 1, res.text)?;
        writeln!(md_file, "- **Tokenized Sequence**: `{:?}`", res.tokens)?;
        writeln!(md_file, "- **Token IDs**: `{:?}`", res.token_ids)?;
        writeln!(md_file, "- **Attention Mask**: `{:?}`", res.attention_mask)?;
        writeln!(md_file, "- **L2 Norm**: `{:.6}` (Unit Sphere verified)", res.l2_norm)?;
        writeln!(md_file, "- **Vector Dimension**: `{}`", res.d_model)?;
        writeln!(md_file, "\n**Embedding Preview (First 8 dims):**")?;
        writeln!(md_file, "```json\n{:?}\n```", res.embedding_sample)?;
        writeln!(md_file, "\n**Complete 64-Dimensional Dense Vector:**")?;
        writeln!(md_file, "```json\n{:?}\n```", res.embedding_full)?;
        writeln!(md_file, "\n---\n")?;
    }

    if !similarities.is_empty() {
        writeln!(md_file, "## Pairwise Semantic Cosine Similarities\n")?;
        writeln!(md_file, "| Sentence A | Sentence B | Cosine Similarity | Semantic Interpretation |")?;
        writeln!(md_file, "|---|---|---|---|")?;
        for (a, b, sim) in similarities {
            let label = if *sim > 0.70 {
                " High Semantic Match (Duplicate / Paraphrase)"
            } else if *sim > 0.30 {
                " Moderate Contextual Overlap"
            } else {
                " Low Similarity / Distinct Topic"
            };
            writeln!(md_file, "| \"{}\" | \"{}\" | **{:.4}** | {} |", a, b, sim, label)?;
        }
    }

    println!(" [FILE SAVED] Formatted presentation report saved to: {}", md_file_path);
    Ok(())
}

