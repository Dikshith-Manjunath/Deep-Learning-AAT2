fn run_demo_benchmark(model: &SentenceTransformer) -> (Vec<SentenceEmbeddingResult>, Vec<(String, String, f32)>) {
    println!("-------------------------------------------------------------------");
    println!(" [DEMO] Running Automated Benchmark on Representative Pairs");
    println!("-------------------------------------------------------------------");

    let test_sentences = vec![
        "Deep learning models use neural networks to learn representations",
        "Artificial intelligence leverages neural architectures for representation learning",
        "Vector databases store embeddings for high dimensional nearest neighbor search",
        "The cat is resting on the living room rug",
    ];

    let mut results = Vec::new();
    for s in &test_sentences {
        let res = model.encode(s);
        println!("\n▶ Text: \"{}\"", res.text);
        println!("  • Tokens: {:?}", res.tokens);
        println!("  • Token IDs: {:?}", res.token_ids);
        println!("  • Embedding Dimension: {}", res.d_model);
        println!("  • Vector Preview [0..8]: {:?}", res.embedding_sample);
        println!("  • Vector L2 Norm: {:.4}", res.l2_norm);
        results.push(res);
    }

    println!("\n-------------------------------------------------------------------");
    println!(" [COSINE SIMILARITY EVALUATION]");
    println!("-------------------------------------------------------------------");

    let pairs = vec![
        (test_sentences[0], test_sentences[1], "Paraphrase Pair (Expected: HIGH)"),
        (test_sentences[0], test_sentences[2], "Related Technical Pair (Expected: MEDIUM/LOW)"),
        (test_sentences[0], test_sentences[3], "Unrelated Domain Pair (Expected: LOW)"),
    ];

    let mut similarity_records = Vec::new();
    for (s1, s2, desc) in pairs {
        let (sim, _, _) = model.compare(s1, s2);
        println!("Pair: \"{}\"\n  vs: \"{}\"", s1, s2);
        println!("  • Description: {}", desc);
        println!("  • Cosine Similarity: {:.4}\n", sim);
        similarity_records.push((s1.to_string(), s2.to_string(), sim));
    }

    (results, similarity_records)
}

fn main() -> io::Result<()> {
    print_header();

    let mut model = build_and_train_model();
    let args: Vec<String> = env::args().collect();

    let mut all_results = Vec::new();
    let mut all_sims = Vec::new();

    // Check if arguments were passed directly on CLI
    if args.len() > 1 {
        let input_text = args[1..].join(" ");
        // Ensure new words are in vocab
        model.tokenizer.build_vocab(&[&input_text]);
        model.update_vocab_size();

        let res = model.encode(&input_text);
        println!("\n=======================================================");
        println!(" [CLI INPUT ENCODED]");
        println!("=======================================================");
        println!(" • Input: \"{}\"", res.text);
        println!(" • Tokens: {:?}", res.tokens);
        println!(" • Embedding Sample [0..8]: {:?}", res.embedding_sample);
        println!(" • L2 Norm: {:.4}", res.l2_norm);
        println!("=======================================================\n");
        all_results.push(res);
    } else {
        // Run demo test first
        let (demo_results, demo_sims) = run_demo_benchmark(&model);
        all_results.extend(demo_results);
        all_sims.extend(demo_sims);

        // Interactive mode: Prompt user to enter text or pairs
        println!("\n=======================================================");
        println!(" [INTERACTIVE MODE] Enter your own sentences to embed");
        println!(" Enter a sentence to calculate its embedding vector.");
        println!(" (Type 'exit' or press Enter on empty line to finish)");
        println!("=======================================================\n");

        let stdin = io::stdin();
        let mut handle = stdin.lock();

        loop {
            print!("Enter sentence > ");
            io::stdout().flush()?;
            let mut line = String::new();
            if handle.read_line(&mut line)? == 0 {
                break;
            }
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.eq_ignore_ascii_case("exit") {
                break;
            }

            // Register words in tokenizer
            model.tokenizer.build_vocab(&[trimmed]);
            model.update_vocab_size();

            let res = model.encode(trimmed);
            println!("\n--- Vector Embedding Generated ---");
            println!("Text: \"{}\"", res.text);
            println!("Tokens: {:?}", res.tokens);
            println!("Vector Preview (First 8 dims): {:?}", res.embedding_sample);
            println!("Full 64-dim Vector Length: {}", res.embedding_full.len());
            println!("L2 Norm: {:.4}\n", res.l2_norm);

            all_results.push(res);
        }
    }

    // Save all computed embeddings and comparisons to files
    save_embeddings_to_files(&all_results, &all_sims)?;

    println!("\n All done! You can now present the architecture and the generated embeddings file to the panel.\n");
    Ok(())
}
